-- Snowflake RBAC beginner lab.
-- Run the entire file in a Snowflake Workspace SQL file as ACCOUNTADMIN.
-- CREATE ... IF NOT EXISTS reuses objects already in your account.

-- 1. Set up compute and a database. A new account may not have these yet.
USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS SNOWFLAKE_LEARNING_DB;
USE WAREHOUSE COMPUTE_WH;

-- 2. Create a schema, a table, and one sample order.
CREATE SCHEMA IF NOT EXISTS SNOWFLAKE_LEARNING_DB.RBAC_LAB;

CREATE TABLE IF NOT EXISTS SNOWFLAKE_LEARNING_DB.RBAC_LAB.ORDERS (
  ORDER_ID NUMBER,
  AMOUNT NUMBER(10, 2)
);

-- Insert order 101 only if it is not already there.
INSERT INTO SNOWFLAKE_LEARNING_DB.RBAC_LAB.ORDERS (ORDER_ID, AMOUNT)
SELECT 101, 49.99
WHERE NOT EXISTS (
  SELECT 1
  FROM SNOWFLAKE_LEARNING_DB.RBAC_LAB.ORDERS
  WHERE ORDER_ID = 101
);

-- 3. Create an analyst role and grant the four permissions needed to query.
CREATE ROLE IF NOT EXISTS RBAC_LAB_ANALYST_ROLE;

GRANT USAGE ON WAREHOUSE COMPUTE_WH
  TO ROLE RBAC_LAB_ANALYST_ROLE;

GRANT USAGE ON DATABASE SNOWFLAKE_LEARNING_DB
  TO ROLE RBAC_LAB_ANALYST_ROLE;

GRANT USAGE ON SCHEMA SNOWFLAKE_LEARNING_DB.RBAC_LAB
  TO ROLE RBAC_LAB_ANALYST_ROLE;

GRANT SELECT ON ALL TABLES IN SCHEMA SNOWFLAKE_LEARNING_DB.RBAC_LAB
  TO ROLE RBAC_LAB_ANALYST_ROLE;

-- 4. Create a practice user and assign the role.
-- No password is stored in this file. The user cannot log in until one is set.
CREATE USER IF NOT EXISTS RAJ_RBAC_LAB
  DEFAULT_ROLE = RBAC_LAB_ANALYST_ROLE
  DEFAULT_WAREHOUSE = COMPUTE_WH
  MUST_CHANGE_PASSWORD = TRUE;

GRANT ROLE RBAC_LAB_ANALYST_ROLE TO USER RAJ_RBAC_LAB;

-- 5. Check the grants, the user's role, and the sample row.
SHOW GRANTS TO ROLE RBAC_LAB_ANALYST_ROLE;
SHOW GRANTS TO USER RAJ_RBAC_LAB;
SELECT * FROM SNOWFLAKE_LEARNING_DB.RBAC_LAB.ORDERS;
