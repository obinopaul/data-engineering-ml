-- Adapted setup excerpt; see ../README.md. Review names/grants before executing.
USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS INTERVIEW_ROLE
    COMMENT = 'Role used by Airflow for the interview workspace';

GRANT ROLE INTERVIEW_ROLE
TO ROLE SYSADMIN;

GRANT USAGE
ON WAREHOUSE COMPUTE_WH
TO ROLE INTERVIEW_ROLE;


GRANT USAGE
ON DATABASE INTERVIEW_DB
TO ROLE INTERVIEW_ROLE;

-- dlt creates a merge staging schema (RAW_STAGING) and its metadata tables.
-- Scope this to your disposable interview database, not a shared source database.
GRANT CREATE SCHEMA ON DATABASE INTERVIEW_DB TO ROLE INTERVIEW_ROLE;




GRANT USAGE, CREATE TABLE, CREATE VIEW
ON SCHEMA INTERVIEW_DB.RAW
TO ROLE INTERVIEW_ROLE;

GRANT USAGE, CREATE TABLE, CREATE VIEW
ON SCHEMA INTERVIEW_DB.STAGING
TO ROLE INTERVIEW_ROLE;

GRANT USAGE, CREATE TABLE, CREATE VIEW
ON SCHEMA INTERVIEW_DB.ANALYTICS
TO ROLE INTERVIEW_ROLE;
